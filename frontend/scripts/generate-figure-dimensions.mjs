import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Read PNG headers only; published figures and research payloads are never rewritten.
const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const roots = [join(frontend, '../runtime/research/product'), join(frontend, 'public/research')];
const dimensions = new Map();
for (const root of roots) {
  if (!existsSync(root)) continue;
  for (const city of readdirSync(root, { withFileTypes: true }).filter(entry => entry.isDirectory())) {
    const figures = join(root, city.name, 'figures');
    if (!existsSync(figures)) continue;
    for (const file of readdirSync(figures).filter(name => name.endsWith('.png')).sort()) {
      const header = readFileSync(join(figures, file));
      if (header.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a' || header.subarray(12, 16).toString() !== 'IHDR') {
        throw new Error(`Invalid PNG header: ${city.name}/${file}`);
      }
      const pair = [header.readUInt32BE(16), header.readUInt32BE(20)];
      if (pair.some(value => value < 1)) throw new Error(`Invalid PNG dimensions: ${city.name}/${file}`);
      const key = `${city.name}/${file}`;
      const existing = dimensions.get(key);
      if (existing && existing.join('/') !== pair.join('/')) throw new Error(`Conflicting published figure: ${key}`);
      dimensions.set(key, pair);
    }
  }
}
if (!dimensions.size) throw new Error('No published research figures found');
const entries = [...dimensions].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const output = `// Generated by scripts/generate-figure-dimensions.mjs from published PNG IHDR headers.\n// Do not edit research images to change layout.\nexport const RESEARCH_FIGURE_DIMENSIONS: Readonly<Record<string, readonly [number, number]>> = {\n${entries.map(([key, [width, height]]) => `  ${JSON.stringify(key)}: [${width}, ${height}],`).join('\n')}\n};\n`;
const target = join(frontend, 'src/domain/research/v2/figureDimensions.ts');
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== output) throw new Error('Figure dimensions are stale; run node scripts/generate-figure-dimensions.mjs');
  console.log(`Verified ${entries.length} published figure dimensions`);
} else {
  writeFileSync(target, output);
  console.log(`Registered ${entries.length} published figure dimensions`);
}
